"""Shared JSON file boundaries for the legacy template library."""
from __future__ import annotations
import json
import os
from pathlib import Path
from tempfile import NamedTemporaryFile


def read_object(path: Path) -> dict | None:
    try:
        value = json.loads(path.read_text(encoding='utf-8'))
    except (OSError, ValueError):
        return None
    return value if isinstance(value, dict) else None


def write_object(path: Path, value: dict) -> None:
    """Replace a complete file atomically; never leave partially written JSON."""
    temporary = None
    try:
        with NamedTemporaryFile(mode='w', encoding='utf-8', dir=path.parent, delete=False) as stream:
            temporary = Path(stream.name)
            json.dump(value, stream, ensure_ascii=False, indent=2)
            stream.flush()
            os.fsync(stream.fileno())
        temporary.replace(path)
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)
